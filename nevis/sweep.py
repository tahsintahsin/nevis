"""Run several configs on one split, score each, and draw the trade-off (closeness x cost x latency).

    python -m nevis.sweep --configs configs/fw_mid_single.yaml configs/fw_large_single.yaml --split validation --judge
    python -m nevis.sweep --report-only --split validation          # just redraw FRONTIER.md / frontier.png from the log

Each config runs into outputs/<config>_<split> (resumable, via nevis.run), is scored into scores/<config>_<split>
and logged to experiments.csv. The frontier is then built from experiments.csv (rows of that split; with --configs
only those runs) and written to FRONTIER.md + frontier.png.
Use --judge for numbers comparable with the reported scores (the same-task gate needs the LLM judge).
"""
import argparse
import json
from pathlib import Path

import pandas as pd

from nevis import experiments

FRONTIER_MD = Path("FRONTIER.md")
FRONTIER_PNG = Path("frontier.png")
# categorical slots 1-2 of the reference palette (dataviz skill), fixed per provider
PROVIDER_COLORS = {"fireworks": "#eb6834", "": "#1baf7a"}


def _p90(row):
    """latency p90: from the log, else from the score folder's summary.json."""
    v = row.get("latency_p90_s")
    if pd.notna(v):
        return v
    f = Path(str(row.get("scores_dir", ""))) / "summary.json"
    if f.exists():
        return json.loads(f.read_text()).get("run", {}).get("latency_p90_s")
    return None


def pareto(df, x, y="north_star"):
    """Rows not beaten on both axes (lower x and higher north star)."""
    ok = df.dropna(subset=[x, y])
    keep = set()
    for i, r in ok.iterrows():
        if not ((ok[x] <= r[x]) & (ok[y] >= r[y]) & ((ok[x] < r[x]) | (ok[y] > r[y]))).any():
            keep.add(i)
    return keep


def frontier_table(split, runs=None, log_csv=None):
    log_csv = Path(log_csv or experiments.LOG_CSV)
    df = pd.read_csv(log_csv).reindex(columns=experiments.COLS)
    df = df[(df.split.astype(str) == split) & (df.provider.astype(str) == "fireworks")]   # only runs made by nevis.run on Fireworks
    if runs:
        df = df[df.run.isin(runs)]
    df = df.drop_duplicates("run", keep="last").copy()
    df["latency_p90_s"] = [_p90(r) for _, r in df.iterrows()]
    for c in ["north_star", "precision", "recall", "cost_per_meeting_usd", "latency_median_s", "latency_p90_s"]:
        df[c] = pd.to_numeric(df[c], errors="coerce")
    return df.sort_values("north_star", ascending=False)


def write_frontier(df, split, md=FRONTIER_MD, png=FRONTIER_PNG):
    md, png = Path(md), Path(png)
    best_cost, best_lat = pareto(df, "cost_per_meeting_usd"), pareto(df, "latency_median_s")
    show = df.assign(pareto=["cost+latency" if i in best_cost and i in best_lat else "cost" if i in best_cost
                             else "latency" if i in best_lat else "" for i in df.index])
    cols = ["run", "provider", "model", "pipeline", "few_shot", "meetings", "north_star", "north_star_95", "precision",
            "recall", "invented", "cost_per_meeting_usd", "latency_median_s", "latency_p90_s", "pareto"]
    L = ["# Trade-off: quality, cost and latency", "",
         f"Meetings: **{split}** set. Generated by `nevis/sweep.py` from `experiments.csv` (don't edit by hand).", "",
         "- **north_star**: how close to the reference (how much of the reference's work each meeting got right, averaged "
         "over meetings; DESIGN.md (b)), with its 95% range.",
         "- **invented**: tickets with a value found in none of the meeting's inputs (guardrail; each flag was checked).",
         "- **cost_per_meeting_usd**: tokens × Fireworks list price (`nevis/runmeta.py`). For the fine-tuned models, which "
         "run on their own GPU, it assumes the GPU is kept fully busy, so it is a best case: at our load it was ~$0.008 "
         "per meeting, and an idle GPU is still billed.",
         "- **latency**: seconds per meeting, from the first model call to the final tickets (median and 90th percentile).",
         "- **pareto**: no other configuration is both better and cheaper (or faster).", "",
         show[cols].fillna("").to_markdown(index=False, floatfmt=".4g"), "",
         f"![frontier]({png.name})", ""]
    md.write_text("\n".join(L))

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.2))
    for ax, x, label, best in [(axes[0], "cost_per_meeting_usd", "cost per meeting (USD, log scale)", best_cost),
                               (axes[1], "latency_median_s", "median latency per meeting (s)", best_lat)]:
        d = df.dropna(subset=[x, "north_star"])
        for prov, g in d.groupby("provider"):
            ax.scatter(g[x], g.north_star, s=48, color=PROVIDER_COLORS.get(prov, "#1baf7a"), label=prov or "other",
                       edgecolors="white", linewidths=1.5, zorder=3)
        front = d.loc[[i for i in d.index if i in best]].sort_values(x)
        if len(front) > 1:
            ax.plot(front[x], front.north_star, color="#8a8a85", linewidth=1, linestyle="--", zorder=2)
        for _, r in d.iterrows():
            ax.annotate(r.run, (r[x], r.north_star), textcoords="offset points", xytext=(5, 4), fontsize=7, color="#3d3d3a")
        if x == "cost_per_meeting_usd" and len(d) and (d[x] > 0).all():
            ax.set_xscale("log")
        if not len(d):
            ax.text(0.5, 0.5, "no runs with this measure yet", ha="center", va="center", transform=ax.transAxes, color="#6b6b66")
        ax.set_xlabel(label, color="#3d3d3a")
        ax.set_ylabel("north star", color="#3d3d3a")
        ax.grid(True, color="#e6e5e0", linewidth=0.8)
        ax.set_axisbelow(True)
        for s in ["top", "right"]:
            ax.spines[s].set_visible(False)
        if len(d):
            ax.legend(frameon=False, fontsize=8, loc="best")
    axes[0].set_title("North star vs cost", loc="left", fontsize=10)
    axes[1].set_title("North star vs latency", loc="left", fontsize=10)
    fig.tight_layout()
    fig.savefig(png, dpi=150, facecolor="white")
    plt.close(fig)
    return md, png


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--configs", nargs="*", default=[])
    ap.add_argument("--split", default="validation")
    ap.add_argument("--meetings", default="dataset")
    ap.add_argument("--splits-file", default="splits.json")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--judge", action="store_true", help="score with the LLM judge on Fireworks (comparable with the reported scores)")
    ap.add_argument("--report-only", action="store_true", help="no runs; rebuild FRONTIER.md/frontier.png from the log")
    a = ap.parse_args(argv)

    runs = []
    if not a.report_only:
        from nevis.data import load_dataset
        from nevis.run import load_config, load_splits, resolve_split, run, score_run
        data, splits = load_dataset(a.meetings), load_splits(a.splits_file)
        ids = resolve_split(a.split, data, splits)[: a.limit or None]
        label = a.split + (f" (first {a.limit})" if a.limit else "")
        for c in a.configs:
            cfg = load_config(c)
            out = Path("outputs") / f"{cfg['name']}_{a.split}"
            res = run(cfg, ids, out, data, splits, split_label=label)
            if res["errors"]:
                print(f"{cfg['name']}: {len(res['errors'])} meetings failed; re-run the sweep to retry them")
            score_run(out, ids, Path("scores") / out.name, data, a.judge, cfg["notes"], label, a.splits_file)
            runs.append(out.name)
        split_key = label
        runs = None                     # the chart shows every logged run of this split, not only this sweep's
    else:
        split_key = a.split
        runs = [Path(c).stem + f"_{a.split}" for c in a.configs] or None
    df = frontier_table(split_key, runs)
    md, png = write_frontier(df, split_key)
    print(df[["run", "north_star", "precision", "recall", "cost_per_meeting_usd", "latency_median_s", "latency_p90_s"]]
          .to_string(index=False))
    print(f"-> {md}, {png}")


if __name__ == "__main__":
    main()
