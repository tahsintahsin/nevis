"""Experiment log: one row per (run, split) in experiments.csv, rendered to EXPERIMENTS.md.

    python -m nevis.experiments --run outputs/<run> --scores scores/<run> --notes "large model, single call"

Reads the run's settings (_run.json written by nevis.run) and the scorer's summary.json. Re-logging the same score folder replaces its row, so the log never has duplicates.
"""
import argparse
import json
import time
from pathlib import Path

import pandas as pd

LOG_CSV = Path("experiments.csv")
LOG_MD = Path("EXPERIMENTS.md")
COLS = ["date", "run", "split", "meetings", "model", "effort", "prompt_version", "judge",
        "north_star", "north_star_95", "precision", "recall", "meetings_without_miss", "template_ok", "dueDate_ok",
        "assignee_ok", "priority_ok", "invented", "cost_per_meeting_usd", "cost_total_usd", "latency_median_s",
        "scores_dir", "notes", "config", "provider", "deployment", "pipeline", "few_shot", "latency_p90_s"]


def settings_of(run_dir):
    run_dir = Path(run_dir)
    rj = run_dir / "_run.json"
    if rj.exists():                      # written by nevis/run.py
        r = json.loads(rj.read_text())
        c = r.get("config", {})
        few = c.get("few_shot", "none")
        return dict(split=r.get("split", ""), model=c.get("model", ""), effort=(c.get("extra_body") or {}).get("reasoning_effort", ""),
                    prompt_version=r.get("prompt_version", ""), config=c.get("name", ""),
                    provider=c.get("provider", ""), deployment=c.get("deployment", ""), pipeline=c.get("pipeline", ""),
                    few_shot=few if few == "none" else f"{few} k={c.get('few_shot_k')}")
    raise SystemExit(f"{run_dir}: no _run.json (only runs made with nevis.run can be logged)")


def log(run_dir, scores_dir, notes="", split=None):
    s = json.loads((Path(scores_dir) / "summary.json").read_text())
    st = settings_of(run_dir)
    run = s.get("run", {})
    row = dict(date=time.strftime("%Y-%m-%d %H:%M"), run=Path(run_dir).name, split=split or st["split"], meetings=s["meetings"],
               model=st["model"], effort=st["effort"], prompt_version=st["prompt_version"],
               judge=s.get("settings", {}).get("judge", ""),
               north_star=round(s["north_star"], 3), north_star_95="–".join(f"{x:.3f}" for x in s.get("north_star_95", [])),
               precision=round(s["precision"], 3), recall=round(s["recall"], 3),
               meetings_without_miss=round(s.get("meetings_without_miss", float("nan")), 3),
               template_ok=round(s.get("template_ok", float("nan")), 3), dueDate_ok=round(s.get("dueDate_ok", float("nan")), 3),
               assignee_ok=round(s.get("assignee_ok", float("nan")), 3), priority_ok=round(s.get("priority_ok", float("nan")), 3),
               invented=s.get("tickets_with_invention"),
               cost_per_meeting_usd=round(run["cost_mean_usd"], 4) if run.get("cost_mean_usd") is not None else None,
               cost_total_usd=round(run["cost_total_usd"], 2) if run.get("cost_total_usd") is not None else None,
               latency_median_s=round(run["latency_median_s"], 1) if run.get("latency_median_s") is not None else None,
               scores_dir=str(scores_dir), notes=notes,
               config=st.get("config", ""), provider=st.get("provider", ""),
               deployment=st.get("deployment", ""), pipeline=st.get("pipeline", "single"), few_shot=st.get("few_shot", "none"),
               latency_p90_s=round(run["latency_p90_s"], 1) if run.get("latency_p90_s") is not None else None)
    df = pd.read_csv(LOG_CSV) if LOG_CSV.exists() else pd.DataFrame(columns=COLS)
    df = df[df.scores_dir != str(scores_dir)]
    df = df.reindex(columns=COLS)
    df = pd.concat([df, pd.DataFrame([row])], ignore_index=True)[COLS]
    df.to_csv(LOG_CSV, index=False)
    render(df)
    return row


def render(df):
    df = df.reindex(columns=COLS)
    show = ["date", "run", "split", "meetings", "model", "effort", "prompt_version", "pipeline", "few_shot", "north_star", "north_star_95",
            "precision", "recall", "meetings_without_miss", "invented", "cost_per_meeting_usd", "cost_total_usd", "notes"]
    LOG_MD.write_text("# Experiment log\n\nOne row per scored run (generated by `nevis/experiments.py` from `experiments.csv`; "
                      "don't edit by hand). north_star = how close to the reference, see DESIGN.md (b). Decisions were made on "
                      "**validation**; each final configuration was run once on **holdout**.\n\n"
                      + df[show].fillna("").to_markdown(index=False) + "\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", required=True)
    ap.add_argument("--scores", required=True)
    ap.add_argument("--split", default=None)
    ap.add_argument("--notes", default="")
    a = ap.parse_args()
    print(log(a.run, a.scores, a.notes, a.split))
